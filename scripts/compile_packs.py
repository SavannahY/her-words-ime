#!/usr/bin/env python3
"""Validate the manifest and deterministically compile packs into inert Lua data."""

import argparse
from pathlib import Path
import sys

try:
    from .validate_packs import DEFAULT_MANIFEST, ValidationError, load_project, normalize_pinyin, surfaces
except ImportError:
    from validate_packs import DEFAULT_MANIFEST, ValidationError, load_project, normalize_pinyin, surfaces


RULE_FIELDS = ("from", "to", "to_traditional", "community", "community_traditional", "match")
ALIAS_FIELDS = ("input", "friendly", "friendly_traditional", "community",
                "community_traditional", "friendly_note", "community_note")


def compile_data(project):
    """Merge explicit community overrides with their required neutral fallback."""
    neutral = {entry["from"]: entry for pack in project.neutral for entry in pack.data["entries"]}
    community = {entry["from"]: entry for pack in project.community for entry in pack.data["entries"]}
    rules, aliases, seen_aliases = [], [], set()
    for source, entry in sorted(neutral.items()):
        override = community.get(source)
        literals = set(surfaces(entry))
        if override:
            literals.update(surfaces(override))
        for literal in sorted(literals):
            rule = {"from": literal, "to": entry["to"], "match": entry["match"]}
            if "to_traditional" in entry:
                rule["to_traditional"] = entry["to_traditional"]
            if override:
                rule["community"] = override["to"]
                if "to_traditional" in override:
                    rule["community_traditional"] = override["to_traditional"]
            rules.append(rule)
        # A pack may omit pinyin when it only contributes phrase rewrites.
        readings = {item["pinyin"] for item in (entry, override)
                    if item is not None and "pinyin" in item}
        for reading in sorted(readings):
            alias = {"input": normalize_pinyin(reading), "friendly": entry["to"]}
            if "to_traditional" in entry:
                alias["friendly_traditional"] = entry["to_traditional"]
            if entry["to"] == "忮忌":
                alias["friendly_note"] = "zhì jì · 近义改写"
            if override:
                alias["community"] = override["to"]
                alias["community_note"] = "借字或拆字写法"
                if "to_traditional" in override:
                    alias["community_traditional"] = override["to_traditional"]
            # Distinct readings can normalize to the same raw Rime segment.
            # Deduplicate equal outputs; retain different suggestions.
            key = tuple(alias.get(field) for field in ALIAS_FIELDS[:5])
            if key not in seen_aliases:
                seen_aliases.add(key)
                aliases.append(alias)
    rules.sort(key=lambda item: item["from"])
    aliases.sort(key=lambda item: tuple(item.get(field, "") for field in ALIAS_FIELDS))
    return {"rules": rules, "exact_aliases": aliases}


def lua_quote(value):
    """Encode every UTF-8 byte as a fixed-width decimal Lua escape.

    Even quotes, NUL, newlines, comment markers and malicious Lua remain data.
    Fixed widths also prevent a following digit from changing escape boundaries.
    """
    return '"' + "".join("\\{:03d}".format(byte) for byte in value.encode("utf-8")) + '"'


def render_lua(data):
    lines = [
        "-- Generated by scripts/compile_packs.py. Edit JSON language packs instead.",
        "-- Strings use decimal UTF-8 byte escapes; this file contains data only.",
        "return {",
    ]
    for section, fields in (("rules", RULE_FIELDS), ("exact_aliases", ALIAS_FIELDS)):
        lines.append("  {} = {{".format(section))
        for item in data[section]:
            values = ["{} = {}".format(field, lua_quote(item[field])) for field in fields if field in item]
            lines.append("    { " + ", ".join(values) + " },")
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def compile_project(project):
    return render_lua(compile_data(project))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        project = load_project(args.manifest)
        output = compile_project(project)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(output, encoding="utf-8")
    except (ValidationError, OSError) as error:
        print("Could not compile language packs: " + str(error), file=sys.stderr)
        return 1
    data = compile_data(project)
    print("Compiled {} rules and {} aliases to {}".format(
        len(data["rules"]), len(data["exact_aliases"]), args.output))
    return 0


if __name__ == "__main__":
    sys.exit(main())
